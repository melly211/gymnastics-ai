const DEEPSEEK_MODEL = 'deepseek-chat'

function compactAnalysisPayload(analysis) {
  const joints = analysis?.joints || {}
  const symmetry = analysis?.symmetry || {}
  const movement = analysis?.movement || {}
  const tracking = analysis?.tracking || {}

  return {
    video: {
      filename: analysis?.video?.filename || 'unknown-video',
      duration: analysis?.video?.duration || 0,
      width: analysis?.video?.width || 0,
      height: analysis?.video?.height || 0,
      analyzedFrames: analysis?.video?.analyzedFrames || 0,
    },
    tracking: {
      detectedFrames: tracking.detectedFrames || 0,
      detectionPercentage: Number(tracking.detectionPercentage ?? 0),
      averageVisibility: Number(tracking.averageVisibility ?? 0),
    },
    joints: {
      leftKnee: joints.leftKnee || { min: 0, max: 0, average: 0, range: 0 },
      rightKnee: joints.rightKnee || { min: 0, max: 0, average: 0, range: 0 },
      leftHip: joints.leftHip || { min: 0, max: 0, average: 0, range: 0 },
      rightHip: joints.rightHip || { min: 0, max: 0, average: 0, range: 0 },
      leftElbow: joints.leftElbow || { min: 0, max: 0, average: 0, range: 0 },
      rightElbow: joints.rightElbow || { min: 0, max: 0, average: 0, range: 0 },
    },
    symmetry: {
      kneeAverageDifference: Number(symmetry.kneeAverageDifference ?? 0),
      hipAverageDifference: Number(symmetry.hipAverageDifference ?? 0),
      elbowAverageDifference: Number(symmetry.elbowAverageDifference ?? 0),
    },
    movement: {
      torsoLeanMin: Number(movement.torsoLeanMin ?? 0),
      torsoLeanMax: Number(movement.torsoLeanMax ?? 0),
      torsoLeanRange: Number(movement.torsoLeanRange ?? 0),
    },
    observations: analysis?.observations || [],
  }
}

export async function generateMovementInterpretation(analysis) {
  const apiKey = import.meta.env.VITE_DEEPSEEK_API_KEY

  if (!apiKey) {
    throw new Error('DeepSeek API key is not configured.')
  }

  const response = await fetch('https://api.deepseek.com/chat/completions', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${apiKey}`,
    },
    body: JSON.stringify({
      model: DEEPSEEK_MODEL,
      temperature: 0.2,
      response_format: { type: 'json_object' },
      messages: [
        {
          role: 'system',
          content:
            'You are a practical gymnastics movement-analysis assistant. You receive objective measurements and rule-based observations generated by pose-tracking software. Return valid JSON with exactly these fields: "summary" (one short plain-language paragraph), "what_went_well" (array of 1-3 concise points), "coaching_feedback" (array of 2-4 objects with "focus", "what_measurements_suggest", and "try_this"), "practice_focus" (array of 2-3 specific, low-risk practice cues), and "tracking_note" (a short limitation note or an empty string). Make the report useful and action-oriented: explain what the athlete can focus on next, with clear body-position cues or simple controlled practice ideas that follow from the observed measurements. Keep feedback specific to the measured joints, symmetry, torso movement, and tracking reliability. Do not invent which skill or event was performed, body movement that was not measured, or causes for the results. Do not repeat degrees, percentages, ranges, or other numerical results in the narrative; those are already shown in the measurements dashboard. Do not diagnose injury, make safety claims, or assert elite/professional technique. Use supportive, conservative language, and say when tracking quality limits interpretation. Keep the sections concise, professional, and easy to act on.',
        },
        {
          role: 'user',
          content: JSON.stringify(compactAnalysisPayload(analysis)),
        },
      ],
    }),
  })

  if (!response.ok) {
    const text = await response.text()
    throw new Error(text || 'DeepSeek report generation failed.')
  }

  const payload = await response.json()
  const content = payload?.choices?.[0]?.message?.content

  if (!content) {
    throw new Error('DeepSeek returned an empty response.')
  }

  try {
    return JSON.parse(content)
  } catch {
    const trimmed = content.trim()
    return {
      summary: trimmed,
      review_points: ['DeepSeek response was returned as plain text and preserved without modification.'],
      coaching_feedback: [],
      practice_focus: [],
      what_went_well: [],
      tracking_note: '',
      raw: trimmed,
    }
  }
}
